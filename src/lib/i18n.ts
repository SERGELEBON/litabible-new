const CONCLUSION_MAP: { fr: string; en: string; es: string }[] = [
  { fr: '– Parole du Seigneur.', en: '– Word of the Lord.', es: '– Palabra del Señor.' },
  { fr: '– Acclamons la Parole de Dieu.', en: '– Let us acclaim the Word of God.', es: '– Aclamemos la Palabra de Dios.' },
  { fr: '– Louange à toi, Seigneur.', en: '– Praise to you, Lord.', es: '– Alabanza a ti, Señor.' },
  { fr: '– Louange à toi, Seigneur Jésus.', en: '– Praise to you, Lord Jesus.', es: '– Alabanza a ti, Señor Jesús.' },
]

export function localizedConclusion(conclusion: string, locale: Locale): string {
  if (locale === 'fr') return conclusion
  const match = CONCLUSION_MAP.find((c) => c.fr === conclusion)
  return match ? match[locale] : conclusion
}
