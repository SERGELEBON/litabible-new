export const translations: Record<Locale, Dict> = { en, fr, es }

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_m, k: string) => {
    const v = vars[k]
    return v === undefined ? `{${k}}` : String(v)
  })
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const v = translations[locale]?.[key] ?? translations.en[key] ?? key
  return interpolate(v, vars)
}

/**
 * React hook returning a `t(key, vars?)` function bound to the current store
 * locale, plus the `locale` itself.
 *
 * Missing keys fall back to English, then to the key itself — never crashes.
 */
export function useT() {
  const locale = useLitabibleStore((s) => s.locale)
  function t(key: string, vars?: Record<string, string | number>): string {
    return translate(locale, key, vars)
  }
  return { t, locale }
}

